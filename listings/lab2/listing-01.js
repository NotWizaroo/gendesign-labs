// Листинг 1 — из методички к лабе 2 (неравномерное распределение: массив с повторами).
// В PDF это «голые» строки; чтобы они запускались в p5, обёрнуты в run().
// Результат печатается на экране; клик — выбрать ещё раз (1 и 3 выпадают в два раза чаще, чем 2).

function setup() {
  noCanvas();
  run();
}

function mousePressed() {
  run();
}

function run() {
  let stuff = [1, 1, 2, 3, 3];
  //1 и 3 сохраняются в массиве дважды, что делает их выбор более вероятным, чем
  //2.
  let value = random(stuff);
  //Выбрать случайный элемент из массива.
  print(value);
}
