// Листинг 2 — из методички к лабе 2 (событие с вероятностью 10%).
// В PDF это «голые» строки; обёрнуты в run(). Клик — бросить ещё раз («Sing!» выпадает в ~10% случаев).

function setup() {
  noCanvas();
  run();
}

function mousePressed() {
  run();
}

function run() {
  let probability = 0.1;
  //Вероятность 10%
  let r = random(1);
  //Случайное число с плавающей точкой от 0 до 1
  if (r < probability) {
    print("Sing!");
  } else {
    print("(тишина, r = " + nf(r, 1, 2) + ")");   // добавлено, чтобы отсутствие события тоже было видно
  }
  //Если случайное число меньше 0,1, пойте!
}
