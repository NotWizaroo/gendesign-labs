// Фрагмент из текста методички к лабе 2 (шум Перлина по оси X во времени).
// В PDF показаны только setup-less строки с draw(); добавлен setup() с холстом, остальное дословно.
// Круг плавно плывёт по горизонтали и оставляет след — в отличие от random(), которое «прыгает».

let t = 0;
//Принято начинать со смещения t = 0, хотя это произвольно.

function setup() {
  createCanvas(640, 360);
  background(255);
}

function draw() {
  let n = noise(t);
  let x = map(n, 0, 1, 0, width);
  //Используется map()для настройки диапазона шума Перлина.
  ellipse(x, 180, 16, 16);
  t += 0.01;
  //Двигайтесь вперед во времени.
}
